/**
 * Builds app/spa-loading-template.html: the static copy of <SplashScreen> that
 * shows while the JS bundle downloads, so the hand-off to the Vue splash is seamless.
 * Re-run after changing SplashScreen.vue, the mascot (packages/garden/src/mascot.ts) or the splash texts:
 *   pnpm gen:loading
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { MASCOT_POSES, MASCOT_STROKE, MASCOT_VIEWBOX, VIEWBOX, plantForDay } from '@motivation/garden'
import { ACCENTS, DEFAULT_SETTINGS } from '../shared/utils/settings.ts'

const SEEDS = [1, 4, 9, 2, 13, 6, 21] // same as SplashScreen.vue
const locale = (lang: string) => JSON.parse(readFileSync(new URL(`../i18n/locales/${lang}.json`, import.meta.url), 'utf8')).splash
const TEXT = { vi: locale('vi'), en: locale('en') }

const mochi = `<svg class="mb-mochi" width="112" height="112" viewBox="${MASCOT_VIEWBOX}" fill="none" stroke="currentColor" stroke-width="${MASCOT_STROKE}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${MASCOT_POSES.wave}</svg>`

const seeds = SEEDS.map((day, i) =>
  `<span style="--d:${(i * 0.28).toFixed(2)}s"><i></i><svg viewBox="${VIEWBOX}">${plantForDay(day).body}</svg></span>`,
).join('')

const accents = JSON.stringify(ACCENTS.map(a => [a.light, a.dark]))

const html = `<!-- Generated by scripts/gen-loading-template.ts. Do not edit by hand. -->
<!-- Shown while the JS bundle loads; looks exactly like <SplashScreen>, which takes over once Vue mounts. -->
<style>
  #mochi-boot{--bg:#E6E5EA;--ink:#1A0DC9;--muted:#8F8AC0;position:fixed;inset:0;z-index:100;display:flex;flex-direction:column;align-items:center;justify-content:center;padding:40px 24px 28px;background:var(--bg);color:var(--ink);font-family:"IBM Plex Mono",ui-monospace,SFMono-Regular,Menlo,monospace;font-size:13px;line-height:1.5;text-align:center;-webkit-font-smoothing:antialiased}
  #mochi-boot.mb-dark{--bg:#15141A;--ink:#968EFF;--muted:#7C77B8}
  #mochi-boot>div{display:flex;flex-direction:column;align-items:center;gap:6px}
  #mochi-boot .mb-mochi{display:block;animation:mb-bob 2.4s ease-in-out infinite}
  #mochi-boot h1{margin:14px 0 0;font-family:"Caveat","Comic Sans MS",cursive;font-size:40px;font-weight:500;line-height:1}
  #mochi-boot p{margin:2px 0 0;font-size:12.5px;line-height:1.375;color:var(--muted)}
  #mochi-boot .mb-seeds{display:flex;gap:6px;margin-top:26px}
  #mochi-boot .mb-seeds span{position:relative;display:grid;place-items:center;width:30px;height:30px}
  #mochi-boot .mb-seeds i{width:4px;height:4px;border-radius:50%;background:currentColor;opacity:.5;animation:mb-dot 3s var(--d) infinite}
  #mochi-boot .mb-seeds svg{position:absolute;inset:0;width:100%;height:100%;transform-origin:50% 90%;transform:scale(0);opacity:0;animation:mb-grow 3s var(--d) infinite}
  #mochi-boot small{display:block;margin-top:14px;font-size:11.5px;line-height:1.375;color:var(--muted)}
  #mochi-boot small b{font-weight:400;animation:mb-blink 1.2s infinite}
  @keyframes mb-bob{0%,100%{transform:translateY(0)}50%{transform:translateY(-6px)}}
  @keyframes mb-dot{0%{opacity:.5;transform:scale(1)}12%,80%{opacity:0;transform:scale(0)}100%{opacity:.5;transform:scale(1)}}
  @keyframes mb-grow{0%{transform:scale(0);opacity:0}14%{transform:scale(1.1);opacity:1}20%,80%{transform:scale(1);opacity:1}92%,100%{transform:scale(0);opacity:0}}
  @keyframes mb-blink{0%,100%{opacity:.2}50%{opacity:1}}
  @media (prefers-reduced-motion:reduce){#mochi-boot *{animation:none!important}#mochi-boot .mb-seeds svg{transform:none;opacity:1}#mochi-boot .mb-seeds i{opacity:0}}
</style>
<div id="mochi-boot" role="status" aria-live="polite">
  <div>
    ${mochi}
    <h1>tiny motivate</h1>
    <p id="mb-tag">${TEXT.vi.tagline}</p>
    <div class="mb-seeds" aria-hidden="true">${seeds}</div>
    <small><span id="mb-load">${TEXT.vi.loading}</span><b>.</b><b style="animation-delay:.2s">.</b><b style="animation-delay:.4s">.</b></small>
  </div>
</div>
<script>
  // Same accent / theme / language the app will use (cached by useSettings on this device).
  (function () {
    var s = {}
    try { s = JSON.parse(localStorage.getItem('motivation-settings') || '{}') } catch (e) {}
    var el = document.getElementById('mochi-boot')
    var theme = s.theme || '${DEFAULT_SETTINGS.theme}'
    var dark = theme === 'dark' || (theme === 'system' && matchMedia('(prefers-color-scheme: dark)').matches)
    var accent = ${accents}[s.accent] || ${accents}[0]
    if (dark) el.classList.add('mb-dark')
    el.style.setProperty('--ink', accent[dark ? 1 : 0])
    var text = ${JSON.stringify(TEXT)}[s.lang] || ${JSON.stringify(TEXT.vi)}
    document.getElementById('mb-tag').textContent = text.tagline
    document.getElementById('mb-load').textContent = text.loading
  })()
  // The public landing page shows its own content straight away.
  if (location.pathname === '/landing-page' || location.pathname === '/privacy') document.getElementById('mochi-boot').remove();
</script>
`

writeFileSync(new URL('../app/spa-loading-template.html', import.meta.url), html)
console.log('wrote app/spa-loading-template.html')
